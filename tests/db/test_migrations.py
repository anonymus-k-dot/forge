"""Alembic migrations against real PostgreSQL (throwaway databases only)."""

import os
import subprocess
import sys
from pathlib import Path

import pytest
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.pool import NullPool

from forge.db import migrate
from forge.db.models import Base

from .conftest import temporary_database

pytestmark = pytest.mark.postgres

REPO_ROOT = Path(__file__).resolve().parents[2]
TABLES = {"workspaces", "runs", "executions", "evaluations"}

SCHEMA_SNAPSHOT_SQL = {
    "columns": """
        SELECT table_name, column_name, data_type, is_nullable, column_default
        FROM information_schema.columns
        WHERE table_schema = 'public' AND table_name <> 'alembic_version'
        ORDER BY 1, 2""",
    "constraints": """
        SELECT conrelid::regclass::text, conname, pg_get_constraintdef(oid)
        FROM pg_constraint
        WHERE connamespace = 'public'::regnamespace
          AND conrelid::regclass::text <> 'alembic_version'
        ORDER BY 1, 2""",
    "indexes": """
        SELECT tablename, indexname, indexdef FROM pg_indexes
        WHERE schemaname = 'public' AND tablename <> 'alembic_version'
        ORDER BY 1, 2""",
}


def schema_snapshot(engine):
    with engine.connect() as connection:
        return {
            k: [tuple(r) for r in connection.execute(text(q))]
            for k, q in SCHEMA_SNAPSHOT_SQL.items()
        }


def test_upgrade_from_empty_database_records_head(empty_database):
    engine = empty_database.engine
    with engine.connect() as connection:
        assert migrate.current_revision(connection) is None
    migrate.upgrade(engine)
    with engine.connect() as connection:
        assert migrate.current_revision(connection) == migrate.head_revision() == "0002"
        assert connection.execute(
            text("SELECT version_num FROM alembic_version")
        ).scalars().all() == ["0002"]
    assert TABLES <= set(inspect(engine).get_table_names())


def test_repeated_upgrade_changes_nothing(empty_database):
    engine = empty_database.engine
    migrate.upgrade(engine)
    before = schema_snapshot(engine)
    migrate.upgrade(engine)
    migrate.upgrade(engine)
    assert schema_snapshot(engine) == before


def test_models_and_migrations_agree_according_to_alembic(empty_database):
    migrate.upgrade(empty_database.engine)
    migrate.check(empty_database.engine)  # raises AutogenerateDiffsDetected on any difference


def test_migrated_schema_equals_model_metadata_including_checks(pg_admin_url, empty_database):
    # alembic check ignores CHECK constraints; compare the catalogs directly instead.
    migrate.upgrade(empty_database.engine)
    with temporary_database(pg_admin_url) as url:
        engine = create_engine(url, poolclass=NullPool)
        try:
            Base.metadata.create_all(engine)  # test-only reference schema, never used in production
            assert schema_snapshot(empty_database.engine) == schema_snapshot(engine)
        finally:
            engine.dispose()


def test_downgrade_and_upgrade_round_trip(empty_database):
    engine = empty_database.engine
    migrate.upgrade(engine)
    snapshot = schema_snapshot(engine)
    migrate.downgrade(engine, "base")
    assert TABLES.isdisjoint(inspect(engine).get_table_names())
    migrate.upgrade(engine)
    assert schema_snapshot(engine) == snapshot


def test_alembic_cli_uses_database_url_and_shows_status(empty_database):
    url = empty_database.settings.url.render_as_string(hide_password=False)
    env = {**os.environ, "DATABASE_URL": url}

    def alembic(*args):
        return subprocess.run(
            [sys.executable, "-m", "alembic", *args],
            cwd=REPO_ROOT,
            env=env,
            capture_output=True,
            text=True,
            timeout=120,
        )

    assert alembic("upgrade", "head").returncode == 0
    current = alembic("current")
    assert current.returncode == 0 and "0002 (head)" in current.stdout
    check = alembic("check")
    assert check.returncode == 0, check.stderr
    for output in (current.stdout + current.stderr, check.stdout + check.stderr):
        assert empty_database.settings.url.password not in output
