"""Alembic helpers usable without ``alembic.ini`` (the migrations ship inside the package)."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.runtime.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy.engine import Connection, Engine

MIGRATIONS_DIR = Path(__file__).resolve().parent / "migrations"


def alembic_config(engine: Engine | None = None) -> Config:
    """Alembic config pointing at the packaged migrations.

    When ``engine`` is given, migrations run on it (its URL is never written into the
    config, so passwords cannot be mangled by or leaked through ``configparser``).
    Otherwise ``env.py`` reads ``DATABASE_URL`` from the environment.
    """
    config = Config()
    config.set_main_option("script_location", str(MIGRATIONS_DIR))
    if engine is not None:
        config.attributes["engine"] = engine
    return config


@lru_cache(maxsize=1)
def head_revision() -> str | None:
    """Latest revision shipped with this code (cached: it cannot change while running)."""
    return ScriptDirectory.from_config(alembic_config()).get_current_head()


def current_revision(connection: Connection) -> str | None:
    return MigrationContext.configure(connection).get_current_revision()


def upgrade(engine: Engine, revision: str = "head") -> None:
    command.upgrade(alembic_config(engine), revision)


def downgrade(engine: Engine, revision: str) -> None:
    command.downgrade(alembic_config(engine), revision)


def check(engine: Engine) -> None:
    """Raise ``alembic.util.exc.AutogenerateDiffsDetected`` if models and migrations differ."""
    command.check(alembic_config(engine))
